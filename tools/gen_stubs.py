"""Generates a logging stub for every import the runtime doesn't implement yet.

Usage: python -I gen_stubs.py <recomp/out> <recomp/runtime>
"""
import glob
import os
import re
import sys


def main(out_dir, runtime_dir):
    with open(os.path.join(out_dir, "ppc_recomp_shared.h"), encoding="latin1") as f:
        imports = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\);", f.read())))
    imports = [name for name in imports if not name.startswith("sub_")]

    implemented = set()
    for path in glob.glob(os.path.join(runtime_dir, "*.cpp")):
        if path.endswith("stubs.gen.cpp"):
            continue
        with open(path, encoding="latin1") as f:
            implemented.update(re.findall(r"^GUEST_IMPORT\((\w+)\)", f.read(), re.M))

    unknown = sorted(implemented - set(imports))
    if unknown:
        sys.exit("implemented but not imported by the game: " + ", ".join(unknown))

    stubs = [name for name in imports if name not in implemented]
    with open(os.path.join(runtime_dir, "stubs.gen.cpp"), "w") as f:
        f.write("// Generated by tools/gen_stubs.py. Do not edit.\n#include \"guest.h\"\n\n")
        for name in stubs:
            f.write('PPC_FUNC(__imp__%s) { StubHit("%s", ctx); ctx.r3.u64 = 0; }\n' % (name, name))
    print("imports: %d implemented, %d stubbed" % (len(implemented), len(stubs)))


main(sys.argv[1], sys.argv[2])
